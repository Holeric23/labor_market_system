-- Preserve source identities and the history of publications and parser runs.
ALTER TABLE sources ADD COLUMN deleted_at timestamptz;
CREATE INDEX sources_active ON sources(id) WHERE deleted_at IS NULL;

CREATE TABLE source_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES sources(id),
    actor_id bigint NOT NULL REFERENCES staff(telegram_id),
    event_type text NOT NULL CHECK(event_type IN ('created','updated','deleted','restored','replaced')),
    details jsonb NOT NULL DEFAULT '{}'::jsonb,
    occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER source_events_immutable BEFORE UPDATE OR DELETE ON source_events
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
