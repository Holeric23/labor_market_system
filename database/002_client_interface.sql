ALTER TABLE app_settings ADD COLUMN services_url text;

CREATE TABLE product_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK(kind IN ('terms','privacy','consent','offer')),
    version text NOT NULL,
    url text NOT NULL,
    body text NOT NULL,
    body_sha256 char(64) NOT NULL,
    published_at timestamptz NOT NULL DEFAULT now(),
    author_id bigint NOT NULL REFERENCES staff(telegram_id),
    UNIQUE(kind,version),
    UNIQUE(kind,id)
);
CREATE TRIGGER product_documents_immutable BEFORE UPDATE OR DELETE ON product_documents
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TABLE current_product_documents (
    kind text PRIMARY KEY,
    document_id bigint NOT NULL,
    FOREIGN KEY(kind,document_id) REFERENCES product_documents(kind,id)
);
CREATE TABLE product_document_acceptances (
    telegram_id bigint NOT NULL REFERENCES clients(telegram_id),
    document_id bigint NOT NULL REFERENCES product_documents(id),
    accepted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(telegram_id,document_id)
);
CREATE TRIGGER product_document_acceptances_immutable BEFORE UPDATE OR DELETE ON product_document_acceptances
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();

CREATE TABLE client_interface_state (
    telegram_id bigint PRIMARY KEY REFERENCES clients(telegram_id),
    active_filter_id uuid REFERENCES saved_filters(id),
    editing_filter_id uuid REFERENCES saved_filters(id),
    draft_filter jsonb NOT NULL DEFAULT '{}'::jsonb,
    draft_name text NOT NULL DEFAULT 'Мой поиск',
    awaiting text,
    wizard_step integer CHECK(wizard_step BETWEEN 0 AND 4),
    pending_token_hash char(64),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE client_vacancies (
    telegram_id bigint NOT NULL REFERENCES clients(telegram_id),
    content_id bigint NOT NULL REFERENCES contents(id),
    saved boolean NOT NULL DEFAULT false,
    hidden boolean NOT NULL DEFAULT false,
    applied boolean NOT NULL DEFAULT false,
    reason text CHECK(reason IN ('specialty','salary','experience','format','other')),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(telegram_id,content_id)
);
CREATE TABLE selections (
    id uuid PRIMARY KEY,
    telegram_id bigint NOT NULL REFERENCES clients(telegram_id),
    result_set_id uuid NOT NULL REFERENCES result_sets(id),
    filter_json jsonb NOT NULL,
    trial boolean NOT NULL,
    status text NOT NULL CHECK(status IN ('pending','delivered','failed','uncertain')),
    request_message_id bigint,
    message_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    delivered_at timestamptz
);
CREATE UNIQUE INDEX one_pending_selection ON selections(telegram_id) WHERE status IN ('pending','uncertain');
CREATE UNIQUE INDEX one_selection_per_request ON selections(telegram_id,request_message_id)
    WHERE request_message_id IS NOT NULL AND status <> 'failed';
CREATE TABLE selection_items (
    selection_id uuid NOT NULL REFERENCES selections(id),
    ordinal integer NOT NULL CHECK(ordinal > 0),
    result_set_id uuid NOT NULL,
    content_id bigint NOT NULL,
    PRIMARY KEY(selection_id,ordinal),
    UNIQUE(selection_id,content_id),
    FOREIGN KEY(result_set_id,content_id) REFERENCES document_results(result_set_id,content_id)
);
