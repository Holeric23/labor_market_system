-- Product schema: source texts are stored once; all times are UTC instants.
CREATE TABLE schema_migrations (
    version integer PRIMARY KEY,
    sha256 char(64) NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE clients (
    telegram_id bigint PRIMARY KEY CHECK (telegram_id > 0),
    display_name text,
    username text,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','blocked')),
    manual_access boolean NOT NULL DEFAULT false,
    access_until timestamptz,
    revision integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE staff (
    telegram_id bigint PRIMARY KEY CHECK (telegram_id > 0),
    role text NOT NULL CHECK (role IN ('owner','manager')),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE app_settings (
    singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
    manager_url text,
    default_access_days integer NOT NULL DEFAULT 30 CHECK(default_access_days BETWEEN 1 AND 3650),
    revision integer NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint REFERENCES staff(telegram_id)
);
INSERT INTO app_settings(singleton) VALUES (true);
CREATE TABLE settings_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL REFERENCES staff(telegram_id),
    previous_values jsonb NOT NULL,
    new_values jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE agreement_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version text NOT NULL UNIQUE,
    url text NOT NULL,
    content_sha256 char(64),
    published_at timestamptz NOT NULL DEFAULT now(),
    is_current boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX one_current_agreement ON agreement_versions(is_current) WHERE is_current;
CREATE TABLE agreement_acceptances (
    telegram_id bigint NOT NULL REFERENCES clients(telegram_id),
    agreement_id bigint NOT NULL REFERENCES agreement_versions(id),
    accepted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (telegram_id, agreement_id)
);

-- An issue may be created before its recipient is known. Redemption is one-use.
CREATE TABLE access_grants (
    id uuid PRIMARY KEY,
    issued_by bigint NOT NULL REFERENCES staff(telegram_id),
    recipient_id bigint REFERENCES clients(telegram_id),
    duration_days integer NOT NULL CHECK (duration_days BETWEEN 1 AND 3650),
    status text NOT NULL CHECK (status IN ('pending','active','cancelled','reverted')),
    issued_at timestamptz NOT NULL DEFAULT now(),
    activated_at timestamptz,
    starts_at timestamptz,
    ends_at timestamptz,
    CHECK (status <> 'active' OR (recipient_id IS NOT NULL AND activated_at IS NOT NULL AND starts_at IS NOT NULL AND ends_at > starts_at))
);
CREATE INDEX access_grants_recipient ON access_grants(recipient_id, ends_at);
CREATE TABLE activation_tokens (
    token_hash char(64) PRIMARY KEY,
    grant_id uuid NOT NULL UNIQUE REFERENCES access_grants(id),
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz,
    consumed_by bigint REFERENCES clients(telegram_id)
);
CREATE TABLE access_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id uuid REFERENCES access_grants(id),
    recipient_id bigint REFERENCES clients(telegram_id),
    actor_id bigint NOT NULL,
    event_type text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    details jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX access_events_recipient ON access_events(recipient_id, id DESC);
CREATE TABLE saved_filters (
    id uuid PRIMARY KEY,
    telegram_id bigint NOT NULL REFERENCES clients(telegram_id),
    name text NOT NULL,
    filter_json jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);
CREATE INDEX saved_filters_owner ON saved_filters(telegram_id) WHERE deleted_at IS NULL;
CREATE TABLE search_sessions (
    telegram_id bigint PRIMARY KEY CHECK(telegram_id > 0),
    filter_json jsonb NOT NULL,
    result_set_id uuid NOT NULL,
    next_offset integer NOT NULL DEFAULT 0 CHECK(next_offset >= 0),
    has_more boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('telegram','designhunters')),
    name text NOT NULL,
    address text NOT NULL,
    parameters jsonb NOT NULL DEFAULT '{}'::jsonb,
    enabled boolean NOT NULL DEFAULT false,
    schedule_enabled boolean NOT NULL DEFAULT false,
    interval_seconds integer NOT NULL DEFAULT 3600 CHECK (interval_seconds >= 60),
    next_run_at timestamptz,
    cursor jsonb NOT NULL DEFAULT '{}'::jsonb,
    revision integer NOT NULL DEFAULT 1,
    last_success_at timestamptz,
    UNIQUE(kind,address)
);
CREATE TABLE parser_runs (
    id uuid PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES sources(id),
    state text NOT NULL CHECK (state IN ('running','succeeded','failed')),
    configuration jsonb NOT NULL DEFAULT '{}'::jsonb,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    inserted_count integer NOT NULL DEFAULT 0 CHECK (inserted_count >= 0),
    error text
);
CREATE UNIQUE INDEX one_active_parser_per_source ON parser_runs(source_id) WHERE state='running';
CREATE TABLE contents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text_sha256 char(64) NOT NULL UNIQUE,
    text text NOT NULL CHECK (length(btrim(text)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE publications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES sources(id),
    external_key text NOT NULL,
    url text NOT NULL,
    current_content_id bigint NOT NULL REFERENCES contents(id),
    published_at timestamptz,
    last_observed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(source_id, external_key)
);
CREATE TABLE publication_revisions (
    publication_id bigint NOT NULL REFERENCES publications(id),
    revision integer NOT NULL CHECK (revision > 0),
    content_id bigint NOT NULL REFERENCES contents(id),
    observed_at timestamptz NOT NULL DEFAULT now(),
    parser_run_id uuid REFERENCES parser_runs(id),
    PRIMARY KEY(publication_id, revision)
);
CREATE TABLE model_versions (
    id text PRIMARY KEY,
    manifest jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE result_sets (
    id uuid PRIMARY KEY,
    model_version text NOT NULL REFERENCES model_versions(id),
    state text NOT NULL CHECK (state IN ('building','ready','failed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    ready_at timestamptz,
    provenance jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE search_sessions ADD CONSTRAINT search_sessions_result_fk FOREIGN KEY (result_set_id) REFERENCES result_sets(id);
CREATE TABLE active_result_set (
    singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
    result_set_id uuid NOT NULL REFERENCES result_sets(id)
);
CREATE TABLE result_set_switches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    previous_id uuid REFERENCES result_sets(id),
    result_set_id uuid NOT NULL REFERENCES result_sets(id),
    switched_at timestamptz NOT NULL DEFAULT now(),
    actor text NOT NULL
);
CREATE TABLE document_results (
    result_set_id uuid NOT NULL REFERENCES result_sets(id),
    content_id bigint NOT NULL REFERENCES contents(id),
    post_type text CHECK(post_type IN ('vacancy','resume')),
    salary_from numeric,
    salary_to numeric,
    currency text,
    salary_period text,
    tax_mode text,
    work_format text,
    schedule text,
    employment_type text,
    evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY(result_set_id, content_id)
);
CREATE INDEX document_results_search ON document_results(result_set_id,post_type,content_id);
CREATE TABLE result_publications (
    result_set_id uuid NOT NULL REFERENCES result_sets(id),
    publication_id bigint NOT NULL REFERENCES publications(id),
    content_id bigint NOT NULL REFERENCES contents(id),
    published_at timestamptz,
    PRIMARY KEY(result_set_id,publication_id),
    FOREIGN KEY(result_set_id,content_id) REFERENCES document_results(result_set_id,content_id)
);
CREATE INDEX result_publications_content ON result_publications(result_set_id,content_id);
CREATE TABLE classes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace text NOT NULL,
    class_key text NOT NULL,
    name text NOT NULL,
    definition_version text NOT NULL,
    UNIQUE(namespace, class_key)
);
CREATE TABLE document_classes (
    result_set_id uuid NOT NULL,
    content_id bigint NOT NULL,
    class_id bigint NOT NULL REFERENCES classes(id),
    role text NOT NULL DEFAULT 'none',
    score real CHECK(score BETWEEN 0 AND 1),
    PRIMARY KEY(result_set_id,content_id,class_id,role),
    FOREIGN KEY(result_set_id,content_id) REFERENCES document_results(result_set_id,content_id)
);
CREATE INDEX document_classes_search ON document_classes(result_set_id,class_id,content_id);
CREATE TABLE corrections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id bigint NOT NULL REFERENCES contents(id),
    revision integer NOT NULL CHECK(revision > 0),
    author_id bigint NOT NULL,
    annotation jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(content_id,revision)
);
CREATE TABLE admin_sessions (
    token_hash char(64) PRIMARY KEY,
    telegram_id bigint REFERENCES staff(telegram_id),
    csrf text NOT NULL,
    expires_at timestamptz NOT NULL
);
CREATE TABLE used_telegram_proofs (
    proof_hash char(64) PRIMARY KEY,
    expires_at timestamptz NOT NULL
);

-- Preserve provenance and history even if an application adapter is faulty.
CREATE FUNCTION reject_history_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'history is append-only';
END $$;
CREATE TRIGGER access_events_immutable BEFORE UPDATE OR DELETE ON access_events
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER settings_history_immutable BEFORE UPDATE OR DELETE ON settings_history
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER result_set_switches_immutable BEFORE UPDATE OR DELETE ON result_set_switches
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER publication_revisions_immutable BEFORE UPDATE OR DELETE ON publication_revisions
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER corrections_immutable BEFORE UPDATE OR DELETE ON corrections
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER contents_immutable BEFORE UPDATE OR DELETE ON contents
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER classes_immutable BEFORE UPDATE OR DELETE ON classes
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER model_versions_immutable BEFORE UPDATE OR DELETE ON model_versions
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER agreements_accepted_immutable BEFORE UPDATE OR DELETE ON agreement_acceptances
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();

CREATE FUNCTION reject_publication_identity_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.source_id IS DISTINCT FROM NEW.source_id OR OLD.external_key IS DISTINCT FROM NEW.external_key OR OLD.url IS DISTINCT FROM NEW.url THEN
        RAISE EXCEPTION 'publication identity is immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER publications_identity_immutable BEFORE UPDATE ON publications
    FOR EACH ROW EXECUTE FUNCTION reject_publication_identity_change();

CREATE FUNCTION reject_finished_result_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.state <> 'building' THEN
        RAISE EXCEPTION 'finished result set is immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER result_sets_immutable BEFORE UPDATE OR DELETE ON result_sets
    FOR EACH ROW EXECUTE FUNCTION reject_finished_result_change();

CREATE FUNCTION reject_finished_result_member_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_set uuid;
    new_set uuid;
BEGIN
    IF TG_OP <> 'INSERT' THEN old_set := OLD.result_set_id; END IF;
    IF TG_OP <> 'DELETE' THEN new_set := NEW.result_set_id; END IF;
    IF (old_set IS NOT NULL AND (SELECT state FROM result_sets WHERE id=old_set) <> 'building') OR
       (new_set IS NOT NULL AND (SELECT state FROM result_sets WHERE id=new_set) <> 'building') THEN
        RAISE EXCEPTION 'finished result set members are immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER document_results_immutable BEFORE INSERT OR UPDATE OR DELETE ON document_results
    FOR EACH ROW EXECUTE FUNCTION reject_finished_result_member_change();
CREATE TRIGGER document_classes_immutable BEFORE INSERT OR UPDATE OR DELETE ON document_classes
    FOR EACH ROW EXECUTE FUNCTION reject_finished_result_member_change();
CREATE TRIGGER result_publications_immutable BEFORE INSERT OR UPDATE OR DELETE ON result_publications
    FOR EACH ROW EXECUTE FUNCTION reject_finished_result_member_change();

CREATE FUNCTION require_ready_active_set() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT state FROM result_sets WHERE id=NEW.result_set_id) IS DISTINCT FROM 'ready' THEN
        RAISE EXCEPTION 'active result set must be ready';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER active_result_ready BEFORE INSERT OR UPDATE ON active_result_set
    FOR EACH ROW EXECUTE FUNCTION require_ready_active_set();
