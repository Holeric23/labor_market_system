-- Collection jobs are shared by the Mini App and the scheduler.
CREATE TABLE collection_jobs (
    id uuid PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES sources(id),
    source_revision integer NOT NULL,
    mode text NOT NULL CHECK(mode IN ('new','history')),
    status text NOT NULL CHECK(status IN ('queued','running','succeeded','failed','cancelled')),
    cancel_requested boolean NOT NULL DEFAULT false,
    requested_by bigint REFERENCES staff(telegram_id),
    requested_at timestamptz NOT NULL DEFAULT now(),
    started_at timestamptz,
    finished_at timestamptz,
    error text,
    parser_run_id uuid REFERENCES parser_runs(id)
);
CREATE UNIQUE INDEX one_collection_job_per_source ON collection_jobs(source_id)
    WHERE status IN ('queued','running');
CREATE INDEX collection_jobs_recent ON collection_jobs(requested_at DESC);

CREATE TABLE collection_worker_status (
    singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
    last_seen_at timestamptz NOT NULL DEFAULT now()
);

