CREATE TABLE retention_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    retention_days integer NOT NULL,
    removed_publications integer NOT NULL,
    removed_contents integer NOT NULL
);
CREATE TRIGGER retention_runs_immutable BEFORE UPDATE OR DELETE ON retention_runs
    FOR EACH ROW EXECUTE FUNCTION reject_history_change();

-- Only explicit retention deletes can remove expired history. Normal mutations
-- of source text, ready results and publication revisions stay prohibited.
CREATE FUNCTION reject_unless_retention_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' AND current_setting('proshe.retention',true)='on' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'history is append-only';
END $$;
DROP TRIGGER contents_immutable ON contents;
CREATE TRIGGER contents_immutable BEFORE UPDATE OR DELETE ON contents
    FOR EACH ROW EXECUTE FUNCTION reject_unless_retention_delete();
DROP TRIGGER publication_revisions_immutable ON publication_revisions;
CREATE TRIGGER publication_revisions_immutable BEFORE UPDATE OR DELETE ON publication_revisions
    FOR EACH ROW EXECUTE FUNCTION reject_unless_retention_delete();
CREATE OR REPLACE FUNCTION reject_finished_result_member_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_set uuid;
    new_set uuid;
BEGIN
    IF TG_OP='DELETE' AND current_setting('proshe.retention',true)='on' THEN
        RETURN OLD;
    END IF;
    IF TG_OP <> 'INSERT' THEN old_set := OLD.result_set_id; END IF;
    IF TG_OP <> 'DELETE' THEN new_set := NEW.result_set_id; END IF;
    IF (old_set IS NOT NULL AND (SELECT state FROM result_sets WHERE id=old_set) <> 'building') OR
       (new_set IS NOT NULL AND (SELECT state FROM result_sets WHERE id=new_set) <> 'building') THEN
        RAISE EXCEPTION 'finished result set members are immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
