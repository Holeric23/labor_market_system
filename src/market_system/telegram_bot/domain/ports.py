from typing import Protocol
from uuid import UUID

from .models import Post, SearchFilter, Subscription, User


class IUserRepository(Protocol):
    async def get_user(self, user_id: int) -> User | None: ...
    async def is_admin(self, user_id: int) -> bool: ...
    async def update(self, user: User) -> None: ...


class IPostRepository(Protocol):
    async def search_posts(self, filter: SearchFilter, limit: int, offset: int) -> list[Post]: ...
    async def count_posts(self, filter: SearchFilter) -> int: ...


class ISubscriptionRepository(Protocol):
    async def create_subscription(self, user_id: int, filter: SearchFilter) -> Subscription: ...
    async def get_user_subscriptions(self, user_id: int) -> list[Subscription]: ...
    # Ownership is required even if a callback contains a valid foreign UUID.
    async def delete_subscription(self, sub_id: UUID, user_id: int) -> bool: ...
    async def find_matching_subscriptions(self, new_post: Post) -> list[int]: ...


class TelegramClient(Protocol):
    async def send_message(self, chat_id: int, text: str, keyboard=None, reply_to: int | None = None) -> int: ...
    async def forward_message(self, chat_id: int, from_chat_id: int | str, message_id: int) -> int: ...
    async def delete_message(self, chat_id: int, message_id: int) -> None: ...


class TelegramError(Exception):
    """Permanent or exhausted Telegram delivery failure."""


class ForwardUnavailable(TelegramError):
    """Original message is unavailable or protected; fallback is permitted."""


class UnsupportedFilter(ValueError):
    """The source schema does not yet persist a requested field."""


class INotificationReceipts(Protocol):
    async def register(self, event_id: UUID, payload: str, recipients: list[int]) -> list[int]: ...
    async def was_delivered(self, post_id: UUID, user_id: int) -> bool: ...
    async def mark_delivered(self, post_id: UUID, user_id: int) -> None: ...
