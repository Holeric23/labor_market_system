"""Notebook section for the second, precision-first architecture experiment."""
import json
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from market_system.research.benchmark import ROOT


def append_report(md, figure, table, first_run):
    pointer = ROOT/'research/results/current_architectures.json'
    if not pointer.exists():
        return
    run = ROOT/json.loads(pointer.read_text(encoding='utf-8'))['path']
    read = lambda name: json.loads((run/name).read_text(encoding='utf-8'))
    architecture = pd.read_csv(run/'architecture_selection.csv')
    models = pd.read_csv(run/'model_selection.csv')
    test = pd.read_csv(run/'retrospective_test.csv')
    selection = read('selection.json')
    cascades = pd.read_csv(run/'cascades.csv')
    cascade = read('cascade_selection.json')
    md('''## 11. Второй эксперимент: архитектура, затем модель

**Новый приоритет: сначала минимизировать ложные назначения вакансий и резюме, затем увеличивать число правильных автоматических решений.**
Это отдельный эксперимент. Победитель первого по macro-F1 не является автоматически подходящим для этого требования.

### Что именно сравнивается

| Архитектура | Обучение | Как получить оценку класса |
|---|---|---|
| multiclass | Одна модель на resume/trash/vacancy | Выход модели для класса |
| two_ovr | Резюме против всех остальных; вакансия против всех остальных | Две независимые оценки; trash — минимум дополнений |
| two_pairs | Резюме против мусора; вакансия против мусора | Выход соответствующей пары; trash должен поддерживаться обеими |
| three_pairs | Две предыдущие пары плюс вакансия против резюме | Минимум оценок всех пар, в которых участвует класс |

Для попарных моделей применяется консервативное согласие, а не обычное голосование sklearn OneVsOneClassifier.
Поэтому выводы относятся к **архитектуре вместе с этим правилом объединения**. В двух попарных моделях отсутствующий
конкурирующий целевой класс не участвует в обучении — это может привести к уверенным ошибкам на нём.
Некоторые алгоритмы, например LinearSVC, уже внутри реализуют многоклассовость через бинарные задачи.

Меньшее число классов не гарантирует меньшую потребность в данных: попарная модель получает меньше примеров,
но граница между двумя близкими классами может оставаться сложной. Нейросеть также проверяется, а не объявляется победителем заранее.

### Протокол и защита от утечки

1. Сохранено прежнее групповое разбиение примерно 60/20/20. Похожие посты не переходят между частями.
2. На обучающих 60% создаются общие для всех методов три групповых фолда. Каждый OOF-прогноз сделан моделью,
   которая не видела этот пост и его группу. TF-IDF и SVD обучаются заново внутри каждой задачи и фолда.
3. На OOF подбираются пороги: ни одного наблюдаемого ложного назначения соответствующего класса,
   минимум 10 принятых примеров, иначе автоматическое назначение этого класса отключается.
4. Для каждого метода архитектура выбирается по OOF: не менее 20 принятых примеров каждой целевой категории,
   затем меньше ложных назначений, затем больше правильных. Эти числа **оптимистичны**, поскольку пороги подобраны здесь же.
5. Выбранные архитектуры сравниваются на общих validation 20%: тот же минимальный объём, меньше FP, больше TP.
   Это выбор кандидата; при ненулевых FP или недостаточном объёме кандидат не удовлетворяет требованию.
6. Старые test 20% используются только для ретроспективной диагностики. Их уже изучали в первом эксперименте;
   они не стали новым независимым тестом. На них ничего не выбирается.

Это ограниченный отбор, а не доказательство универсально лучшей архитектуры: один набор внешних частей,
три внутренних фолда, фиксированные гиперпараметры и конкретное правило агрегации.
Следующий более дорогой этап — повторная вложенная групповая кросс-валидация с подбором параметров внутри каждой архитектуры.

На validation/test усредняются выходы трёх моделей фолдов: это одинаковый для всех вариантов ансамбль,
обученный на разных подвыборках. Он позволяет проверить идею разнообразия обучающих данных.
Разница между единичным OOF-прогнозом и средним трёх прогнозов может менять шкалу — качество переноса порогов проверяется отдельно.
Seeds зафиксированы. Менять лишь random_state детерминированной модели недостаточно для разнообразия.
Параметры базовых моделей фиксированы: здесь исследуется архитектура, а не повторяется широкий подбор гиперпараметров.

**Оценки не откалиброваны.** Для моделей без predict_proba применено монотонное преобразование decision_function;
их числа нельзя читать как вероятность правильного ответа. Для неоднозначного или недостаточно уверенного результата
есть отдельный ответ `uncertain`. Он никогда автоматически не превращается в `trash`.
''')
    md('### Выбор архитектуры для каждого метода\n\n'+table(models[['model','architecture','target_fp','target_tp','resume_precision','vacancy_precision','coverage']])+'''

Это результаты validation после выбора архитектуры на OOF. Precision без принятых примеров не определён.
Coverage включает уверенно принятый мусор; target_tp и target_recall относятся только к вакансиям и резюме.
''')
    md('### Подробно: логистическая регрессия и MLP\n\n'
       +table(architecture[architecture.model.isin(['word_lr','char_lr','word_char_lr','mlp_lsa'])]
              [['model','architecture','forced_macro_f1','target_tp','target_recall']])
       +'''\n\nforced_macro_f1 — дополнительная диагностика при принудительном выборе максимальной оценки;
она не используется для выбора. target_tp и target_recall получены после строгих порогов.
Низкое значение здесь может означать, что почти все ответы отклоняются, даже если обычный macro-F1 высок.
Порог — часть системы; сравнение только обычного predict() отвечало бы на другой вопрос.

Небольшое преимущество по одному OOF-разбиению не доказывает устойчивое превосходство:
в частности, разницу в несколько принятых постов следует проверять повторными разбиениями.
Для методов, которые не принимают целевые классы при строгих порогах, выбранное имя архитектуры
является лишь разрешением ничьей; подходящей рабочей архитектуры этим запуском не найдено.

Три класса не заставляют модель записывать неопределённость в мусор. Это определяется правилом решения.
Здесь право отказаться от ответа дано всем архитектурам, чтобы преимущество двух шкал не возникало
только из-за того, что одна система может отказываться, а другая обязана отвечать.
''')
    pivot = architecture.pivot(index='model', columns='architecture', values='target_recall')
    plt.figure(figsize=(9,7))
    plt.imshow(pivot.to_numpy(), aspect='auto', vmin=0, vmax=1, cmap='YlGnBu')
    plt.yticks(range(len(pivot)), pivot.index)
    plt.xticks(range(len(pivot.columns)), pivot.columns, rotation=20)
    plt.colorbar(label='OOF recall: thresholds fitted on these predictions')
    plt.title('Architecture screening — optimistic OOF recall')
    figure('architecture_oof', 'Полнота после подбора порогов на OOF')
    winner = selection['winner']
    diagnosed = test[test.model==winner['model']].iloc[0]
    md(f"### Выбор модели\n\nКандидат по правилу validation: **{winner['model']} / {winner['architecture']}**. "
       f"Ноль FP при достаточном числе принятых примеров на validation: **{selection['qualified_on_validation']}**. "
       "Это не гарантия отсутствия ошибок в будущем и не команда заменять рабочую модель.\n\n"
       + table(test[['model','architecture','target_fp','target_tp','resume_precision','vacancy_precision','resume_recall','vacancy_recall']]))
    md(f"**Вывод по выбранному кандидату:** на validation {winner['target_fp']} ложных целевых назначений "
       f"при {winner['target_tp']} правильных; на старом тесте {int(diagnosed.target_fp)} ложных "
       f"при {int(diagnosed.target_tp)} правильных. Полнота целевых классов на старом тесте "
       f"{diagnosed.target_recall:.1%}. "
       "Нулевой результат на подборочной части не даёт гарантии на новых данных. "
       "Неопределённые ответы требуют проверки; автоматическую замену рабочей системы по этому исследованию не выполняем.")
    if (run/'label_audit.csv').exists():
        audit = pd.read_csv(run/'label_audit.csv')
        md('### Проверка спорной исходной метки\n\n'
           +table(audit[['text_hash','label','prediction','review_status']])
           +'''\n\nПри чтении ошибочно классифицированного по исходной разметке поста обнаружено возможное противоречие:
автор предлагает услуги веб-дизайна, приводит портфолио и описывает собственный опыт, тогда как исходная метка — vacancy.
Модель ответила resume. Это **предположение о дефекте метки, требующее проверки человеком**.
Исходные метки, разбиения и числа выше сохранены. Нельзя исправить тест по предсказанию модели
и затем выдать улучшившуюся оценку за независимое подтверждение. Полный текст сохранён в label_audit.csv.
''')
    positions = np.arange(len(test))
    plt.figure(figsize=(10,5))
    plt.bar(positions-.18, test.resume_fp, width=.36, label='False resume')
    plt.bar(positions+.18, test.vacancy_fp, width=.36, label='False vacancy')
    plt.xticks(positions, test.model, rotation=60, ha='right')
    plt.ylabel('False assignments on reused test'); plt.legend()
    figure('architecture_false_positives', 'Ложные срабатывания на старом тесте')
    selected = cascades[(cascades.gate==cascade['gate']) & (cascades.specialist==cascade['specialist'])]
    md('''### Каскад: широкий вход, строгий выход

Проверена идея двух разных рабочих режимов. Первая модель отсекает только посты с очень высокой оценкой мусора:
порог поставлен так, чтобы на OOF не потерять ни одной вакансии или резюме. Вторая принимает целевую категорию
только по строгому порогу. Отклонённые первой моделью посты остаются uncertain, а не объявляются достоверным мусором.
Это эксперимент с порогами, а не специальной асимметричной функцией потерь.

Перебраны все упорядоченные пары выбранных архитектур, включая один метод в двух режимах.
Лучший каскад выбран по validation тем же правилом; test не участвует в выборе.
'''+table(selected[['split','gate','specialist','target_fp','target_tp','target_recall','coverage']])+'''

Каскад может уменьшить FP, но может также потерять полезные посты. Сам по себе он не создаёт информацию:
если модели уверенно ошибаются на одном шаблоне, два порога ошибку не исправят.
''')
    base = models[models.model==cascade['specialist']].iloc[0]
    md(f"У выбранного каскада на validation изменение относительно его строгой модели без входного фильтра: "
       f"FP {int(cascade['target_fp']-base.target_fp):+d}, TP {int(cascade['target_tp']-base.target_tp):+d}. "
       "При равенстве качества проще оставить одну строгую модель. Равные результаты каскадов разрешаются "
       "порядком перебора; это не свидетельство уникального преимущества выбранной пары.")
    from market_system.research.policy_comparison import append_comparison
    append_comparison(md, table, first_run, run)
    md(f'''### Как повторить

```powershell
.venv-library/Scripts/python.exe -m research.architectures
.venv-library/Scripts/python.exe -m research.run
```

Первая команда создаёт новый каталог, вторая обновляет общий ноутбук. Обычный запуск research.run
переиспользует последний завершённый архитектурный эксперимент. Исходные рабочие модели не заменяются.
Артефакты: `{run.relative_to(ROOT).as_posix()}`. Сохранены разбиения, scores всех архитектур, пороги,
выборы, ошибки, предупреждения, исходный скрипт и его SHA-256.

Для дальнейшего подтверждения нужна свежая случайная выборка из всего потока, включая ранее отклонённые посты.
Существующая очередь проверки извлечения содержит уже отобранные вакансии/резюме и не заменяет такую проверку классификации.

Источники: [многоклассовые стратегии](https://scikit-learn.org/stable/modules/multiclass.html),
[подбор порогов](https://scikit-learn.org/stable/modules/classification_threshold.html).
''')
